import { expect, test } from '@playwright/test';
import { sessionFixture } from '../db/sessionFixture';

for (const role of ['teacher', 'admin'] as const) test(`${role} preview lessons follow module order and filter exercises before opening work`, async ({ page }) => {
  const f = await sessionFixture(role);
  let extraLessonId: string | undefined;
  try {
    const original = await f.admin.from('exercises').select('lesson_id').eq('id', f.exerciseId).single();
    expect(original.error).toBeNull();
    const originalLessonId = original.data!.lesson_id;
    // Global lesson order deliberately disagrees with this module's order.
    const lesson = await f.admin.from('lessons').insert({ teacher_id: f.teacherId, slug: 'later-globally', title: 'Pierwsza w module', publication_status: 'approved', position: 100 }).select('id').single();
    expect(lesson.error).toBeNull();
    extraLessonId = lesson.data!.id;
    expect((await f.admin.from('module_lessons').update({ position: 2 }).eq('module_id', f.moduleId).eq('lesson_id', originalLessonId)).error).toBeNull();
    expect((await f.admin.from('module_lessons').insert({ module_id: f.moduleId, lesson_id: extraLessonId, position: 1 })).error).toBeNull();
    const exercise = await f.admin.from('exercises').insert({ lesson_id: extraLessonId, slug: 'first', title: 'Zadanie pierwszej lekcji', position: 1, instructions_markdown: 'Pierwsze zadanie', starter_code: 'print("pierwsza")', runtime_type: 'python-console' }).select('id').single();
    expect(exercise.error).toBeNull();
    expect((await f.admin.from('student_work').insert({ student_id: f.studentId, exercise_id: f.exerciseId, code: 'print("na żywo")', status: 'in_progress' })).error).toBeNull();
    // A second assignment path must not duplicate lessons or exercises.
    expect((await f.admin.from('student_module_assignments').insert({ student_id: f.studentId, module_id: f.moduleId })).error).toBeNull();
    await page.goto('/login');
    await page.getByLabel('Adres e-mail').fill(f.teacherEmail);
    await page.getByLabel('Hasło').fill(f.password);
    await page.getByRole('button', { name: 'Zaloguj się', exact: true }).click();
    await expect(page).toHaveURL(new RegExp(`/${role}$`));
    await page.goto(`/${role}/classes/${f.classId}/live?student=${f.studentId}`);
    const lessons = page.getByLabel('Lekcja ucznia');
    const exercises = page.getByLabel('Ćwiczenie ucznia');
    const editor = page.getByRole('textbox', { name: 'Kod Python ucznia (tylko do odczytu)' });
    const liveButton = page.getByRole('button', { name: 'Podgląd na żywo', exact: true });
    await expect(liveButton).toHaveAttribute('aria-pressed', 'true');
    await expect(liveButton).toHaveCSS('background-color', 'rgb(38, 131, 88)');
    const studentPickerBox = (await page.getByLabel('Podgląd ucznia').boundingBox())!;
    const liveButtonBox = (await liveButton.boundingBox())!;
    const lessonPickerBox = (await lessons.boundingBox())!;
    expect(studentPickerBox.x + studentPickerBox.width).toBeLessThanOrEqual(liveButtonBox.x);
    expect(liveButtonBox.x + liveButtonBox.width).toBeLessThanOrEqual(lessonPickerBox.x);
    await expect(lessons.locator('option')).toHaveText(['Wybierz lekcję', 'Pierwsza w module', 'Lekcja sesji']);
    await expect(exercises).toBeDisabled();
    await expect(editor).toHaveText('print("na żywo")');
    await lessons.selectOption(extraLessonId);
    await expect(liveButton).toHaveAttribute('aria-pressed', 'false');
    await expect(exercises.locator('option')).toHaveText(['Wybierz ćwiczenie', 'Zadanie pierwszej lekcji (Nierozpoczęte)']);
    await expect(editor).toHaveCount(0);
    await exercises.selectOption(exercise.data!.id);
    await expect(editor).toHaveText('print("pierwsza")');
    const instructions = page.getByRole('complementary', { name: 'Treść ćwiczenia' });
    const toggle = page.getByRole('button', { name: 'Treść ćwiczenia', exact: true });
    await expect(instructions).toBeHidden();
    await expect(toggle).toHaveAttribute('aria-expanded', 'false');
    await toggle.click();
    await expect(instructions).toBeVisible();
    const instructionsBox = (await instructions.boundingBox())!;
    const editorBox = (await page.locator('.live-preview-editor').boundingBox())!;
    const outputBox = (await page.locator('.live-preview-output').boundingBox())!;
    expect(instructionsBox.x + instructionsBox.width).toBeLessThanOrEqual(editorBox.x + 1);
    expect(editorBox.x + editorBox.width).toBeLessThanOrEqual(outputBox.x + 1);
    await toggle.click();
    await expect(instructions).toBeHidden();
    expect((await page.locator('.live-preview-editor').boundingBox())!.width).toBeGreaterThan(editorBox.width);
    await page.getByRole('button', { name: 'Uruchom', exact: true }).click();
    await expect(page.getByTestId('stdout')).toHaveText('pierwsza\n');
    await page.screenshot({ path: `test-results/${role}-preview-lessons-desktop.png`, fullPage: true });
    await page.setViewportSize({ width: 390, height: 844 });
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
    await page.screenshot({ path: `test-results/${role}-preview-lessons-mobile.png`, fullPage: true });
    await liveButton.click();
    await expect(liveButton).toHaveAttribute('aria-pressed', 'true');
    await expect(lessons).toHaveValue('');
    await expect(exercises).toBeDisabled();
    await expect(editor).toHaveText('print("na żywo")');
    await lessons.selectOption(originalLessonId);
    await expect(exercises).toHaveValue('');
    await expect(exercises.locator('option')).toHaveText(['Wybierz ćwiczenie', 'Kod sesji (W trakcie)']);
    await exercises.selectOption(f.exerciseId);
    await expect(editor).toHaveText('print("na żywo")');
    await page.getByLabel('Podgląd ucznia').selectOption('');
    await expect(lessons).toBeDisabled();
    await expect(editor).toHaveCount(0);
    await page.getByLabel('Podgląd ucznia').selectOption(f.studentId);
    await expect(editor).toHaveText('print("na żywo")');
    await liveButton.click();
    await expect(exercises).toBeDisabled();
    await expect(editor).toHaveText('print("na żywo")');
  } finally {
    if (extraLessonId) await f.admin.from('lessons').delete().eq('id', extraLessonId);
    await f.cleanup();
  }
});
